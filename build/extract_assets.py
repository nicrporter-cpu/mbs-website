#!/usr/bin/env python3
"""Pull the third-party assets this site needs out of the MBS design system.

The design system's mockups load React, ReactDOM and Babel from unpkg.com and their
webfonts from fonts.googleapis.com — so those pages need an internet connection. Its
`mockups/standalone/*.html` files, however, already carry every one of those files
inlined as gzipped base64 in a `__bundler/manifest` block. This script unpacks them:

    vendor/react.development.js, react-dom.development.js, babel.min.js
    fonts/fonts.css   (Fraunces + DM Sans, embedded as data: URIs)

Fonts are embedded rather than written as separate .woff2 files because Chrome refuses
to load font files over file://, and this site is meant to survive a double-click.
Both families are variable fonts: Google serves one file per unicode subset and points
every weight at it, so the per-weight rules are collapsed into one rule per subset with
a weight *range*.

Usage:  python3 build/extract_assets.py ["/path/to/MBS Design System"]
"""

import base64
import glob
import gzip
import hashlib
import json
import os
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_DS = pathlib.Path.home() / 'Downloads' / 'MBS Design System'

VENDOR_NAMES = ['react.development.js', 'react-dom.development.js', 'babel.min.js']
# Weight ranges the site actually uses, from the design system's Google Fonts import.
WEIGHT_RANGE = {'DM Sans': '300 800', 'Fraunces': '400 700'}


def read_bundle(path):
    src = path.read_text(encoding='utf-8')
    manifest = json.loads(re.search(r'<script type="__bundler/manifest"[^>]*>(.*?)</script>', src, re.S).group(1))
    template = json.loads(re.search(r'<script type="__bundler/template"[^>]*>(.*?)</script>', src, re.S).group(1))
    return manifest, template


def blob(entry):
    raw = base64.b64decode(entry['data'])
    return gzip.decompress(raw) if entry.get('compressed') else raw


def extract_vendor(ds):
    manifest, template = read_bundle(ds / 'mockups' / 'standalone' / 'home.html')
    # The three CDN <script> tags keep their order in the template: react, react-dom, babel.
    uuids = re.findall(r'<script src="([0-9a-f-]{36})"[^>]*integrity=', template)
    if len(uuids) != len(VENDOR_NAMES):
        sys.exit(f'expected {len(VENDOR_NAMES)} vendor scripts, found {len(uuids)}')
    (ROOT / 'vendor').mkdir(exist_ok=True)
    for uuid, name in zip(uuids, VENDOR_NAMES):
        data = blob(manifest[uuid])
        (ROOT / 'vendor' / name).write_bytes(data)
        print(f'  vendor/{name:<28} {len(data):>9,} bytes')


def extract_fonts(ds):
    """One rule per (family, unicode-range); identical font blobs are stored once."""
    rules = {}
    for path in sorted(glob.glob(str(ds / 'mockups' / 'standalone' / '*.html'))):
        manifest, template = read_bundle(pathlib.Path(path))
        for face in re.findall(r'@font-face\s*\{.*?\}', template, re.S):
            uuid = re.search(r'url\("([0-9a-f-]{36})"\)', face)
            if not uuid or uuid.group(1) not in manifest:
                continue  # rule whose font was never inlined — nothing to self-host
            family = re.search(r"font-family:\s*'([^']+)'", face).group(1)
            urange = re.search(r'unicode-range:\s*([^;]+);', face).group(1).strip()
            rules.setdefault((family, urange), blob(manifest[uuid.group(1)]))

    out = ["/* MBS webfonts — Fraunces (display serif) + DM Sans (UI/body).",
           "   Generated by build/extract_assets.py from the design system's standalone bundles;",
           "   replaces its Google Fonts import so the site renders identically offline and when",
           "   opened straight from disk. Variable fonts: one rule per unicode subset, all weights.",
           "   Do not edit by hand. */"]
    for (family, urange), data in sorted(rules.items()):
        out.append('@font-face {\n'
                   f"  font-family: '{family}';\n"
                   '  font-style: normal;\n'
                   f'  font-weight: {WEIGHT_RANGE.get(family, "400 700")};\n'
                   '  font-display: swap;\n'
                   f'  src: url("data:font/woff2;base64,{base64.b64encode(data).decode()}") format(\'woff2\');\n'
                   f'  unicode-range: {urange};\n'
                   '}')
    (ROOT / 'fonts').mkdir(exist_ok=True)
    for stale in (ROOT / 'fonts').glob('*.woff2'):
        stale.unlink()
    css = '\n'.join(out) + '\n'
    (ROOT / 'fonts' / 'fonts.css').write_text(css, encoding='utf-8')
    total = sum(len(d) for d in rules.values())
    print(f'  fonts/fonts.css  {len(rules)} rules, {total:,} bytes of font data '
          f'({len(css):,} bytes as base64)')


def main():
    ds = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_DS
    if not (ds / 'mockups' / 'standalone').is_dir():
        sys.exit(f'design system not found at {ds}\n'
                 f'usage: python3 build/extract_assets.py "/path/to/MBS Design System"')
    print(f'source: {ds}')
    extract_vendor(ds)
    extract_fonts(ds)


if __name__ == '__main__':
    main()
